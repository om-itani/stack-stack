//! Cloud-init NoCloud seed generation.
//!
//! Every value here comes from a validated [`VmConfig`]: hostname, login user,
//! password, SSH keys and the static/DHCP network choice. The three emitted
//! files (`user-data`, `meta-data`, `network-config`) are exactly what the
//! NoCloud datasource looks for on the `CIDATA` volume, and the volume itself is
//! built in-process by [`super::iso9660`], so a guest can be provisioned with no
//! external tooling at all.
//!
//! YAML is written by hand, which means every interpolated value is quoted and
//! stripped of control characters first: a password or key can never break out
//! of its scalar and inject a directive.

use crate::virtualization::iso9660::{self, IsoFile};
use crate::virtualization::model::{NetMode, VmConfig};

/// Rendered seed files.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Seed {
    pub user_data: String,
    pub meta_data: String,
    /// Only present for a static address: cloud-init defaults to DHCP otherwise.
    pub network_config: Option<String>,
}

/// Render the three NoCloud files for a VM.
pub fn render(vm: &VmConfig) -> Seed {
    Seed {
        user_data: user_data(vm),
        meta_data: meta_data(vm),
        network_config: network_config(vm),
    }
}

/// Build the `CIDATA` seed ISO for a VM.
pub fn build_iso(vm: &VmConfig) -> Vec<u8> {
    let seed = render(vm);
    let mut files = vec![
        IsoFile {
            name: "user-data",
            data: seed.user_data.as_bytes(),
        },
        IsoFile {
            name: "meta-data",
            data: seed.meta_data.as_bytes(),
        },
    ];
    if let Some(network) = seed.network_config.as_deref() {
        files.push(IsoFile {
            name: "network-config",
            data: network.as_bytes(),
        });
    }
    iso9660::build("CIDATA", &files)
}

fn user_data(vm: &VmConfig) -> String {
    let mut out = String::with_capacity(512);
    out.push_str("#cloud-config\n");
    out.push_str("# Generated by stack-stack. Manual edits are overwritten.\n");

    let hostname = vm.hostname();
    out.push_str(&format!("hostname: {}\n", quote(&hostname)));
    out.push_str(&format!("fqdn: {}\n", quote(&hostname)));
    out.push_str("manage_etc_hosts: true\n");
    out.push_str("preserve_hostname: false\n");
    out.push_str("package_update: false\n");
    out.push_str("package_upgrade: false\n");

    let username = clean_scalar(&vm.cloud_init.username);
    let username = if username.is_empty() {
        "stack".to_string()
    } else {
        username
    };

    out.push_str("users:\n");
    out.push_str(&format!("  - name: {}\n", quote(&username)));
    out.push_str(&format!("    gecos: {}\n", quote(&username)));
    out.push_str("    groups: [sudo, adm]\n");
    out.push_str("    shell: /bin/bash\n");
    out.push_str("    lock_passwd: false\n");
    out.push_str("    sudo: ['ALL=(ALL) NOPASSWD:ALL']\n");

    let keys: Vec<String> = vm
        .cloud_init
        .ssh_keys
        .iter()
        .map(|key| clean_scalar(key))
        .filter(|key| !key.is_empty())
        .collect();
    if !keys.is_empty() {
        out.push_str("    ssh_authorized_keys:\n");
        for key in &keys {
            out.push_str(&format!("      - {}\n", quote(key)));
        }
    }

    // `chpasswd.list` is a literal block: one `user:password` line. The password
    // is stripped of newlines so it cannot terminate the block early.
    let password = clean_scalar(&vm.cloud_init.password);
    if !password.is_empty() {
        out.push_str("chpasswd:\n");
        out.push_str("  expire: false\n");
        out.push_str("  list: |\n");
        out.push_str(&format!("    {username}:{password}\n"));
        out.push_str("ssh_pwauth: true\n");
    } else {
        out.push_str("ssh_pwauth: false\n");
    }

    // Root stays locked: the created user already has passwordless sudo.
    out.push_str("disable_root: true\n");
    out
}

fn meta_data(vm: &VmConfig) -> String {
    let mut out = String::with_capacity(128);
    out.push_str("#cloud-config\n");
    out.push_str(&format!(
        "instance-id: {}\n",
        quote(&format!("stack-{}-1", vm.id))
    ));
    out.push_str(&format!("local-hostname: {}\n", quote(&vm.hostname())));
    out.push_str("dsmode: local\n");
    out
}

/// Netplan v2, matched on the MAC so it works whatever the guest names the NIC.
fn network_config(vm: &VmConfig) -> Option<String> {
    let mode = vm.cloud_init.ip_mode;
    if mode == NetMode::None {
        return None;
    }

    let mac = vm.effective_mac();
    let mut out = String::with_capacity(256);
    out.push_str("version: 2\n");
    out.push_str("ethernets:\n");
    out.push_str("  main0:\n");
    out.push_str("    match:\n");
    out.push_str(&format!("      macaddress: {}\n", quote(&mac)));
    out.push_str("    set-name: eth0\n");

    match mode {
        NetMode::Dhcp => {
            out.push_str("    dhcp4: true\n");
            if !vm.cloud_init.dns.is_empty() {
                out.push_str("    nameservers:\n");
                out.push_str("      addresses:\n");
                for server in &vm.cloud_init.dns {
                    out.push_str(&format!("        - {}\n", quote(server)));
                }
            }
        }
        NetMode::Static => {
            out.push_str("    dhcp4: false\n");
            let address = vm.cloud_init.address.clone().unwrap_or_default();
            out.push_str("    addresses:\n");
            out.push_str(&format!("      - {}\n", quote(&address)));
            if !vm.cloud_init.gateway.trim().is_empty() {
                out.push_str("    routes:\n");
                out.push_str("      - to: default\n");
                out.push_str(&format!(
                    "        via: {}\n",
                    quote(vm.cloud_init.gateway.trim())
                ));
            }
            if !vm.cloud_init.dns.is_empty() {
                out.push_str("    nameservers:\n");
                out.push_str("      addresses:\n");
                for server in &vm.cloud_init.dns {
                    out.push_str(&format!("        - {}\n", quote(server)));
                }
            }
        }
        NetMode::None => return None,
    }

    Some(out)
}

/// Single-quoted YAML scalar. Single quotes inside are doubled, which is the
/// only escape YAML single quotes recognise.
fn quote(value: &str) -> String {
    format!("'{}'", clean_scalar(value).replace('\'', "''"))
}

/// Remove anything that would break a single-line scalar: control characters
/// (including CR/LF) are dropped, and the result is length-bounded.
fn clean_scalar(value: &str) -> String {
    value
        .chars()
        .filter(|c| !c.is_control())
        .take(512)
        .collect::<String>()
        .trim()
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::virtualization::model::CloudInitConfig;

    fn vm() -> VmConfig {
        VmConfig {
            id: "web".to_string(),
            cloud_init: CloudInitConfig {
                enabled: true,
                hostname: String::new(),
                username: "stack".to_string(),
                password: "hunter2".to_string(),
                ssh_keys: vec!["ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIabc user@host".to_string()],
                ..CloudInitConfig::default()
            },
            ..VmConfig::default()
        }
    }

    #[test]
    fn user_data_sets_hostname_user_and_password() {
        let seed = render(&vm());
        assert!(seed.user_data.starts_with("#cloud-config"));
        assert!(seed.user_data.contains("hostname: 'web'"));
        assert!(seed.user_data.contains("name: 'stack'"));
        assert!(seed.user_data.contains("    stack:hunter2\n"));
        assert!(seed.user_data.contains("ssh_pwauth: true"));
        assert!(seed.user_data.contains("disable_root: true"));
        assert!(
            seed.user_data
                .contains("ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIabc user@host")
        );
    }

    #[test]
    fn meta_data_names_the_instance() {
        let seed = render(&vm());
        assert!(seed.meta_data.contains("instance-id: 'stack-web-1'"));
        assert!(seed.meta_data.contains("local-hostname: 'web'"));
    }

    #[test]
    fn dhcp_still_gets_an_explicit_interface() {
        // An explicit DHCP config is emitted (rather than nothing) so the guest
        // NIC is named deterministically from the MAC.
        let net = render(&vm()).network_config.expect("dhcp config");
        assert!(net.contains("dhcp4: true"));
        assert!(net.contains("set-name: eth0"));
    }

    #[test]
    fn static_network_config_is_netplan_v2() {
        let mut config = vm();
        config.cloud_init.ip_mode = NetMode::Static;
        config.cloud_init.address = Some("192.168.1.50/24".to_string());
        config.cloud_init.gateway = "192.168.1.1".to_string();
        config.cloud_init.dns = vec!["1.1.1.1".to_string(), "9.9.9.9".to_string()];

        let seed = render(&config);
        let net = seed.network_config.expect("static config");
        assert!(net.contains("version: 2"));
        assert!(net.contains("dhcp4: false"));
        assert!(net.contains("'192.168.1.50/24'"));
        assert!(net.contains("to: default"));
        assert!(net.contains("via: '192.168.1.1'"));
        assert!(net.contains("'1.1.1.1'"));
        // Matched on the derived MAC.
        assert!(net.contains(&config.effective_mac()));
    }

    #[test]
    fn a_password_with_a_newline_cannot_break_the_block() {
        let mut config = vm();
        config.cloud_init.password = "evil\n  malicious: true".to_string();
        let seed = render(&config);
        // The injected directive is collapsed onto the single password line, so
        // it can never become a directive of its own.
        assert!(!seed.user_data.contains("\n    malicious: true"));
        assert!(seed.user_data.contains("stack:evil"));
        assert!(seed.user_data.contains("malicious: true\n"));
    }

    #[test]
    fn quotes_in_values_are_escaped() {
        let mut config = vm();
        config.cloud_init.hostname = "we'b".to_string();
        let seed = render(&config);
        assert!(seed.user_data.contains("hostname: 'we''b'"));
    }

    #[test]
    fn the_seed_iso_contains_all_three_files() {
        let mut config = vm();
        config.cloud_init.ip_mode = NetMode::Static;
        config.cloud_init.address = Some("10.0.0.5/24".to_string());
        config.cloud_init.gateway = "10.0.0.1".to_string();

        let iso = build_iso(&config);
        assert_eq!(iso.len() % 2048, 0);
        for name in ["user-data", "meta-data", "network-config"] {
            let needle: Vec<u8> = name.encode_utf16().flat_map(u16::to_be_bytes).collect();
            assert!(
                iso.windows(needle.len()).any(|window| window == needle),
                "{name} missing from the ISO"
            );
        }
    }
}
