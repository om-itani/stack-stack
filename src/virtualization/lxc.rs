//! LXC container generation.
//!
//! Containers are created with `lxc-create -t download` and then given a
//! stack-stack generated `config` file, so the network, cgroup limits, id map
//! and bind mounts are exactly what the operator asked for and nothing else.
//! Like the QEMU generator this is pure text/argv, which is what makes it
//! testable without a Linux host or root.
//!
//! Everything is scoped with `-P <guests_dir>/lxc`, so nothing leaks into
//! `/var/lib/lxc` and the whole guest set stays in one tree that can be backed
//! up or deleted as a unit.

use std::fmt::Write;

use crate::config::Config;
use crate::virtualization::model::{CtConfig, NetMode};
use crate::virtualization::store;

/// Host id range reserved for unprivileged containers. `100000` is the
/// conventional base; the deploy script maps it in `/etc/subuid` and `/etc/subgid`.
pub const IDMAP_HOST_BASE: u32 = 100_000;
/// Number of ids mapped into an unprivileged container.
pub const IDMAP_COUNT: u32 = 65_536;

/// The `-a` value for `lxc-create -t download`.
pub fn download_arch(arch: &str) -> &'static str {
    match arch {
        "arm64" => "arm64",
        _ => "amd64",
    }
}

/// The `lxc.arch` personality value.
pub fn lxc_arch(arch: &str) -> &'static str {
    match arch {
        "arm64" => "arm64",
        _ => "linux64",
    }
}

/// Render the container `config` file.
pub fn render_config(cfg: &Config, ct: &CtConfig) -> String {
    let rootfs = store::ct_dir(cfg, &ct.id).join("rootfs");
    let mut out = String::with_capacity(1024);
    let _ = writeln!(
        out,
        "# Generated by stack-stack. Manual edits are overwritten."
    );

    let _ = writeln!(out, "lxc.uts.name = {}", ct.hostname());
    let _ = writeln!(out, "lxc.arch = {}", lxc_arch(&ct.arch));
    let _ = writeln!(out, "lxc.rootfs.path = dir:{}", rootfs.display());
    let _ = writeln!(out, "lxc.autodev = 1");
    let _ = writeln!(out, "lxc.tty.max = 4");
    let _ = writeln!(out, "lxc.pty.max = 1024");

    // AppArmor: the generated profile is the safe default; nesting needs a
    // permissive profile because inner sandboxes stack their own policy.
    if ct.nesting {
        let _ = writeln!(out, "lxc.apparmor.profile = unconfined");
        let _ = writeln!(out, "lxc.mount.auto = proc:rw sys:rw cgroup:mixed");
    } else {
        let _ = writeln!(out, "lxc.apparmor.profile = generated");
        let _ = writeln!(out, "lxc.mount.auto = proc:mixed sys:mixed cgroup:mixed");
    }

    if ct.unprivileged {
        for line in idmap_lines() {
            let _ = writeln!(out, "{line}");
        }
    } else {
        let _ = writeln!(out, "# privileged container: no id map");
    }

    render_network(&mut out, ct);
    render_limits(&mut out, ct);
    render_binds(&mut out, ct);

    for capability in &ct.cap_drop {
        let _ = writeln!(out, "lxc.cap.drop = {capability}");
    }

    render_startup(&mut out, ct);
    out
}

fn render_network(out: &mut String, ct: &CtConfig) {
    if ct.ip_mode == NetMode::None {
        let _ = writeln!(out, "lxc.net.0.type = none");
        return;
    }

    let _ = writeln!(out, "lxc.net.0.type = veth");
    let _ = writeln!(out, "lxc.net.0.link = {}", ct.bridge);
    let _ = writeln!(out, "lxc.net.0.flags = up");
    let _ = writeln!(out, "lxc.net.0.name = eth0");
    let _ = writeln!(out, "lxc.net.0.hwaddr = {}", ct.effective_mac());

    if ct.ip_mode == NetMode::Static {
        if let Some(address) = &ct.address {
            let _ = writeln!(out, "lxc.net.0.ipv4.address = {address}");
        }
        if !ct.gateway.trim().is_empty() {
            let _ = writeln!(out, "lxc.net.0.ipv4.gateway = {}", ct.gateway.trim());
        }
    }
    // For DHCP the address is deliberately left unset: the container's own init
    // (ifupdown / systemd-networkd) asks the bridge's dnsmasq for a lease.
}

fn render_limits(out: &mut String, ct: &CtConfig) {
    let _ = writeln!(out, "lxc.cgroup2.memory.max = {}", ct.memory_bytes());
    if ct.swap_mb > 0 {
        // Swap limit includes memory on cgroup v2, so add the two together.
        let swap = u64::from(ct.memory_mb + ct.swap_mb) * 1024 * 1024;
        let _ = writeln!(out, "lxc.cgroup2.memory.swap.max = {swap}");
    } else {
        let _ = writeln!(out, "lxc.cgroup2.memory.swap.max = 0");
    }
    if let Some((quota, period)) = ct.cpu_max() {
        let _ = writeln!(out, "lxc.cgroup2.cpu.max = {quota} {period}");
    }
    let _ = writeln!(out, "lxc.cgroup2.pids.max = 8192");
}

fn render_binds(out: &mut String, ct: &CtConfig) {
    for bind in &ct.binds {
        // LXC wants the container side relative to the rootfs, and bind mounts
        // need `create=dir` so the target exists.
        let target = bind.target.trim_start_matches('/');
        let mut options = String::from("bind,create=dir");
        if bind.readonly {
            options.push_str(",ro");
        }
        let _ = writeln!(
            out,
            "lxc.mount.entry = {} {} none {} 0 0",
            bind.source, target, options
        );
    }
}

fn render_startup(out: &mut String, ct: &CtConfig) {
    if ct.autostart {
        let _ = writeln!(out, "lxc.start.auto = 1");
        let _ = writeln!(out, "lxc.start.order = {}", ct.startup_order);
        let _ = writeln!(out, "lxc.start.delay = {}", ct.startup_delay);
    } else {
        let _ = writeln!(out, "lxc.start.auto = 0");
    }
}

/// The unprivileged id map: container ids `0..65536` map to host ids
/// `100000..165536` for both user and group, which is what keeps a container
/// root confined to an unprivileged slice of the host.
pub fn idmap_lines() -> Vec<String> {
    vec![
        format!("lxc.idmap = u 0 {IDMAP_HOST_BASE} {IDMAP_COUNT}"),
        format!("lxc.idmap = g 0 {IDMAP_HOST_BASE} {IDMAP_COUNT}"),
    ]
}

/// `/etc/hosts`-style line: `127.0.1.1 <hostname>`.
pub fn hosts_line(ct: &CtConfig) -> String {
    format!("127.0.1.1 {}\n", ct.hostname())
}

/// `/etc/resolv.conf` contents from the configured DNS servers, or `None` to
/// leave whatever the template wrote.
pub fn resolv_conf(ct: &CtConfig) -> Option<String> {
    if ct.dns.is_empty() {
        return None;
    }
    let mut out = String::from("# Generated by stack-stack.\n");
    for server in &ct.dns {
        let _ = writeln!(out, "nameserver {server}");
    }
    Some(out)
}

// ---------------------------------------------------------------------------
// argv builders
// ---------------------------------------------------------------------------

/// Every `lxc-*` invocation shares this prefix so the whole guest set stays in
/// one storage pool.
fn prefix(cfg: &Config) -> Vec<String> {
    vec!["-P".to_string(), store::lxc_root(cfg).display().to_string()]
}

/// `lxc-create`, using the download template.
pub fn create_argv(
    cfg: &Config,
    ct: &CtConfig,
    dist: &str,
    release: &str,
    mirror: Option<&str>,
) -> Vec<String> {
    let mut args = prefix(cfg);
    push(&mut args, &["-n", &ct.id]);
    push(&mut args, &["-B", "dir"]);
    push(&mut args, &["-t", "download"]);
    args.push("--".to_string());
    push(&mut args, &["-d", dist]);
    push(&mut args, &["-r", release]);
    push(&mut args, &["-a", download_arch(&ct.arch)]);
    if let Some(mirror) = mirror {
        push(&mut args, &["--mirror", mirror]);
    }
    args
}

pub fn start_argv(cfg: &Config, id: &str) -> Vec<String> {
    let mut args = prefix(cfg);
    push(&mut args, &["-n", id, "-d"]);
    args
}

/// `lxc-stop`. `kill` escalates immediately; otherwise a 30 second grace period
/// is allowed for the guest to run its shutdown scripts.
pub fn stop_argv(cfg: &Config, id: &str, kill: bool) -> Vec<String> {
    let mut args = prefix(cfg);
    push(&mut args, &["-n", id]);
    if kill {
        push(&mut args, &["-k"]);
    } else {
        push(&mut args, &["--timeout", "30"]);
    }
    args
}

pub fn destroy_argv(cfg: &Config, id: &str) -> Vec<String> {
    let mut args = prefix(cfg);
    push(&mut args, &["-n", id, "-f"]);
    args
}

pub fn info_argv(cfg: &Config, id: &str) -> Vec<String> {
    let mut args = prefix(cfg);
    push(&mut args, &["-n", id, "-H"]);
    args
}

pub fn attach_argv(cfg: &Config, id: &str, command: &[&str]) -> Vec<String> {
    let mut args = prefix(cfg);
    push(&mut args, &["-n", id]);
    args.push("--".to_string());
    args.extend(command.iter().map(|part| (*part).to_string()));
    args
}

fn push(args: &mut Vec<String>, parts: &[&str]) {
    for part in parts {
        args.push((*part).to_string());
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::virtualization::model::BindMount;

    fn temp_cfg(name: &str) -> Config {
        let dir =
            std::env::temp_dir().join(format!("stack-stack-lxc-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        Config {
            guests_dir: dir.join("guests").to_string_lossy().into_owned(),
            ..Config::default()
        }
    }

    fn ct() -> CtConfig {
        CtConfig {
            id: "db".to_string(),
            template: "debian".to_string(),
            cores: 2,
            memory_mb: 1024,
            swap_mb: 512,
            ..CtConfig::default()
        }
    }

    #[test]
    fn config_carries_the_essentials() {
        let config = render_config(&temp_cfg("config"), &ct());
        assert!(config.contains("lxc.uts.name = db"));
        assert!(config.contains("lxc.arch = linux64"));
        assert!(config.contains("lxc.rootfs.path = dir:"));
        assert!(config.contains("lxc.net.0.link = br0"));
        assert!(config.contains("lxc.net.0.type = veth"));
        assert!(config.contains("lxc.cgroup2.memory.max = 1073741824"));
        assert!(config.contains("lxc.cgroup2.cpu.max = 200000 100000"));
        assert!(config.contains("lxc.cgroup2.pids.max = 8192"));
        // Unprivileged is the default, so the id map is present.
        assert!(config.contains("lxc.idmap = u 0 100000 65536"));
    }

    #[test]
    fn privileged_containers_have_no_id_map() {
        let mut config = ct();
        config.unprivileged = false;
        let rendered = render_config(&temp_cfg("priv"), &config);
        assert!(rendered.contains("privileged container: no id map"));
        assert!(!rendered.contains("lxc.idmap"));
    }

    #[test]
    fn swap_limit_adds_memory_and_swap() {
        let config = render_config(&temp_cfg("swap"), &ct());
        // (1024 + 512) MiB.
        assert!(config.contains("lxc.cgroup2.memory.swap.max = 1610612736"));
        let mut no_swap = ct();
        no_swap.swap_mb = 0;
        assert!(
            render_config(&temp_cfg("nsw"), &no_swap).contains("lxc.cgroup2.memory.swap.max = 0")
        );
    }

    #[test]
    fn unlimited_cpu_omits_the_quota() {
        let mut config = ct();
        config.cores = 0;
        let rendered = render_config(&temp_cfg("nocpu"), &config);
        assert!(!rendered.contains("cpu.max"));
    }

    #[test]
    fn dhcp_leaves_the_address_unset_but_static_sets_it() {
        let dhcp = render_config(&temp_cfg("dhcp"), &ct());
        assert!(!dhcp.contains("ipv4.address"));

        let mut static_ct = ct();
        static_ct.ip_mode = NetMode::Static;
        static_ct.address = Some("192.168.1.50/24".to_string());
        static_ct.gateway = "192.168.1.1".to_string();
        let rendered = render_config(&temp_cfg("static"), &static_ct);
        assert!(rendered.contains("lxc.net.0.ipv4.address = 192.168.1.50/24"));
        assert!(rendered.contains("lxc.net.0.ipv4.gateway = 192.168.1.1"));
    }

    #[test]
    fn no_networking_uses_type_none() {
        let mut config = ct();
        config.ip_mode = NetMode::None;
        let rendered = render_config(&temp_cfg("none"), &config);
        assert!(rendered.contains("lxc.net.0.type = none"));
        assert!(!rendered.contains("veth"));
    }

    #[test]
    fn binds_are_relative_and_can_be_readonly() {
        let mut config = ct();
        config.binds = vec![
            BindMount {
                source: "/srv/data".to_string(),
                target: "/mnt/data".to_string(),
                readonly: false,
            },
            BindMount {
                source: "/srv/media".to_string(),
                target: "/media".to_string(),
                readonly: true,
            },
        ];
        let rendered = render_config(&temp_cfg("binds"), &config);
        assert!(
            rendered.contains("lxc.mount.entry = /srv/data mnt/data none bind,create=dir 0 0"),
            "{rendered}"
        );
        assert!(
            rendered.contains("lxc.mount.entry = /srv/media media none bind,create=dir,ro 0 0")
        );
    }

    #[test]
    fn nesting_switches_to_a_permissive_profile() {
        let mut config = ct();
        config.nesting = true;
        let rendered = render_config(&temp_cfg("nesting"), &config);
        assert!(rendered.contains("lxc.apparmor.profile = unconfined"));
        assert!(rendered.contains("proc:rw sys:rw"));
    }

    #[test]
    fn cap_drop_and_autostart_render() {
        let mut config = ct();
        config.cap_drop = vec!["NET_ADMIN".to_string()];
        config.autostart = true;
        config.startup_order = 3;
        config.startup_delay = 5;
        let rendered = render_config(&temp_cfg("caps"), &config);
        assert!(rendered.contains("lxc.cap.drop = NET_ADMIN"));
        assert!(rendered.contains("lxc.start.auto = 1"));
        assert!(rendered.contains("lxc.start.order = 3"));
        assert!(rendered.contains("lxc.start.delay = 5"));
    }

    #[test]
    fn idmap_is_the_standard_unprivileged_range() {
        let lines = idmap_lines();
        assert_eq!(lines[0], "lxc.idmap = u 0 100000 65536");
        assert_eq!(lines[1], "lxc.idmap = g 0 100000 65536");
    }

    #[test]
    fn resolv_conf_follows_the_dns_list() {
        let mut config = ct();
        assert!(resolv_conf(&config).is_none());
        config.dns = vec!["1.1.1.1".to_string(), "9.9.9.9".to_string()];
        let rendered = resolv_conf(&config).expect("resolv");
        assert!(rendered.contains("nameserver 1.1.1.1"));
        assert!(rendered.contains("nameserver 9.9.9.9"));
    }

    #[test]
    fn create_argv_targets_the_download_template() {
        let args = create_argv(&temp_cfg("create"), &ct(), "debian", "bookworm", None);
        assert!(args.contains(&"-t".to_string()));
        assert!(args.contains(&"download".to_string()));
        assert!(args.windows(2).any(|w| w == ["-d", "debian"]));
        assert!(args.windows(2).any(|w| w == ["-r", "bookworm"]));
        assert!(args.windows(2).any(|w| w == ["-a", "amd64"]));
        // The storage pool prefix is always present.
        assert_eq!(args[0], "-P");
    }

    #[test]
    fn lifecycle_argv_shape() {
        let cfg = temp_cfg("lifecycle");
        assert!(start_argv(&cfg, "db").contains(&"-d".to_string()));
        assert!(
            stop_argv(&cfg, "db", false)
                .windows(2)
                .any(|w| w == ["--timeout", "30"])
        );
        assert!(stop_argv(&cfg, "db", true).contains(&"-k".to_string()));
        assert!(destroy_argv(&cfg, "db").contains(&"-f".to_string()));
        let info = info_argv(&cfg, "db");
        assert!(info.contains(&"-H".to_string()));
    }

    #[test]
    fn attach_runs_a_command_after_the_separator() {
        let args = attach_argv(&temp_cfg("attach"), "db", &["/bin/sh"]);
        let separator = args.iter().position(|a| a == "--").expect("--");
        assert_eq!(args[separator + 1], "/bin/sh");
    }
}
