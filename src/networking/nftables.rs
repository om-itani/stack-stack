//! nftables ruleset generation.
//!
//! The generated ruleset is a single `inet` table, so IPv4 and IPv6 share one
//! policy, with three filter chains (input/forward/output) and two NAT chains
//! (dstnat/prerouting, srcnat/postrouting).
//!
//! Two invariants the ruleset must always hold, because breaking either locks
//! the operator out of the box they are configuring:
//!
//! * replies to connections the router itself started are accepted, and
//! * the configured management ports stay reachable from every LAN.

use std::fmt::Write;

use crate::networking::ipmath::Ipv4Net;
use crate::networking::model::{FirewallRule, NetworkConfig};

/// Name of the single generated table; `nft -f` replaces its contents wholesale.
pub const TABLE: &str = "stackstack";

pub fn render(config: &NetworkConfig) -> String {
    let lan_interfaces = config.lan_interfaces();
    let lan_networks: Vec<Ipv4Net> = config.lan_networks();
    let wan = config.wan_interface();

    let mut out = String::with_capacity(2048);
    let _ = writeln!(
        out,
        "# Generated by stack-stack. Manual edits are overwritten."
    );
    let _ = writeln!(out, "table inet {TABLE} {{");

    render_sets(&mut out, &lan_networks);
    render_input(&mut out, config, &lan_interfaces, &lan_networks);
    render_forward(&mut out, config, wan, &lan_networks);
    render_output(&mut out);
    render_postrouting(&mut out, wan);
    render_prerouting(&mut out, config, wan);

    let _ = writeln!(out, "}}");
    out
}

fn render_sets(out: &mut String, lan_networks: &[Ipv4Net]) {
    if lan_networks.is_empty() {
        return;
    }
    let elements = lan_networks
        .iter()
        .map(Ipv4Net::network_cidr)
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(out, "  set lan_nets {{");
    let _ = writeln!(out, "    type ipv4_addr");
    let _ = writeln!(out, "    flags interval");
    let _ = writeln!(out, "    elements = {{ {elements} }}");
    let _ = writeln!(out, "  }}");
}

fn render_input(
    out: &mut String,
    config: &NetworkConfig,
    lan_interfaces: &[String],
    lan_networks: &[Ipv4Net],
) {
    let firewall = &config.firewall;
    let _ = writeln!(out, "  chain input {{");
    let _ = writeln!(
        out,
        "    type filter hook input priority filter; policy {};",
        firewall.default_input.as_verdict()
    );
    let _ = writeln!(out, "    iifname \"lo\" accept");

    if firewall.allow_established {
        let _ = writeln!(out, "    ct state established,related accept");
        let _ = writeln!(out, "    ct state invalid drop");
    }
    if firewall.allow_icmp {
        let _ = writeln!(out, "    ip protocol icmp accept");
        let _ = writeln!(out, "    ip6 nexthdr icmpv6 accept");
    }

    let management = port_set(&firewall.management_ports);

    if let Some(lan_match) = lan_interface_match(lan_interfaces) {
        // DHCP and DNS are what the LAN needs from the router itself.
        let _ = writeln!(out, "    iifname {lan_match} udp dport 67 accept");
        let _ = writeln!(out, "    iifname {lan_match} udp dport 53 accept");
        let _ = writeln!(out, "    iifname {lan_match} tcp dport 53 accept");

        if let Some(ports) = &management {
            let _ = writeln!(out, "    # management ports stay reachable from the LAN");
            let _ = writeln!(
                out,
                "    iifname {lan_match} tcp dport {{ {ports} }} accept"
            );
        }
    } else if let Some(ports) = &management {
        let _ = writeln!(
            out,
            "    # no LAN interface configured; management ports are open to any source"
        );
        let _ = writeln!(out, "    tcp dport {{ {ports} }} accept");
    }

    let lan_set = if lan_networks.is_empty() {
        None
    } else {
        Some("@lan_nets")
    };
    for rule in firewall.rules.iter().filter(|rule| rule.enabled) {
        let _ = writeln!(out, "    {}", render_rule(rule, lan_set));
    }

    let _ = writeln!(out, "  }}");
}

fn render_forward(
    out: &mut String,
    config: &NetworkConfig,
    wan: Option<&str>,
    lan_networks: &[Ipv4Net],
) {
    let _ = writeln!(out, "  chain forward {{");
    let _ = writeln!(
        out,
        "    type filter hook forward priority filter; policy drop;"
    );
    let _ = writeln!(out, "    ct state established,related accept");

    // LAN -> anywhere. Expressed with the address set when one exists so the
    // rule does not depend on interface naming.
    if !lan_networks.is_empty() {
        let _ = writeln!(out, "    ip saddr @lan_nets accept");
    } else if let Some(match_expr) = lan_interface_match(&config.lan_interfaces()) {
        let _ = writeln!(out, "    iifname {match_expr} accept");
    }

    // Inbound connections we DNAT'ed are legitimate, and already scoped to the
    // ports the operator chose to forward.
    let forwards_enabled = config.port_forwards.iter().any(|forward| forward.enabled);
    if forwards_enabled {
        match wan {
            Some(wan) => {
                let _ = writeln!(out, "    iifname \"{wan}\" ct status dnat accept");
            }
            None => {
                let _ = writeln!(out, "    # port forwards are enabled but no WAN is set");
                let _ = writeln!(out, "    ct status dnat accept");
            }
        }
    }

    let _ = writeln!(out, "  }}");
}

fn render_output(out: &mut String) {
    let _ = writeln!(out, "  chain output {{");
    let _ = writeln!(
        out,
        "    type filter hook output priority filter; policy accept;"
    );
    let _ = writeln!(out, "  }}");
}

fn render_postrouting(out: &mut String, wan: Option<&str>) {
    let _ = writeln!(out, "  chain postrouting {{");
    let _ = writeln!(
        out,
        "    type nat hook postrouting priority srcnat; policy accept;"
    );
    match wan {
        Some(wan) => {
            let _ = writeln!(out, "    oifname \"{wan}\" masquerade");
        }
        None => {
            let _ = writeln!(out, "    # no WAN interface configured; NAT is not applied");
        }
    }
    let _ = writeln!(out, "  }}");
}

fn render_prerouting(out: &mut String, config: &NetworkConfig, wan: Option<&str>) {
    let _ = writeln!(out, "  chain prerouting {{");
    let _ = writeln!(
        out,
        "    type nat hook prerouting priority dstnat; policy accept;"
    );
    for forward in config
        .port_forwards
        .iter()
        .filter(|forward| forward.enabled)
    {
        let mut rule = String::new();
        if let Some(wan) = wan {
            let _ = write!(rule, "iifname \"{wan}\" ");
        }
        let _ = write!(
            rule,
            "{} dport {} dnat to {}:{}",
            forward.protocol, forward.external_port, forward.internal_ip, forward.internal_port
        );
        if let Some(comment) = sanitize_comment(&forward.comment) {
            let _ = write!(rule, " comment \"{comment}\"");
        }
        let _ = writeln!(out, "    {rule}");
    }
    let _ = writeln!(out, "  }}");
}

fn render_rule(rule: &FirewallRule, lan_set: Option<&str>) -> String {
    let mut parts: Vec<String> = Vec::new();
    match rule.source.as_deref() {
        Some(source) => {
            if let Ok(net) = Ipv4Net::parse(source) {
                parts.push(format!("ip saddr {}", net.network_cidr()));
            }
        }
        None => {
            // No explicit source: scope the rule to the LAN set so a
            // hand-written rule cannot accidentally expose the WAN.
            if let Some(set) = lan_set {
                parts.push(format!("ip saddr {set}"));
            }
        }
    }

    match rule.protocol.as_str() {
        "icmp" => parts.push("ip protocol icmp".to_string()),
        protocol => match rule.port {
            Some(port) => parts.push(format!("{protocol} dport {port}")),
            None => parts.push(format!("meta l4proto {protocol}")),
        },
    }

    parts.push(rule.action.as_verdict().to_string());
    let mut rendered = parts.join(" ");
    if let Some(comment) = sanitize_comment(&rule.comment) {
        let _ = write!(rendered, " comment \"{comment}\"");
    }
    rendered
}

/// `{ 22, 8553 }`, or `None` when the list is empty.
fn port_set(ports: &[u16]) -> Option<String> {
    if ports.is_empty() {
        None
    } else {
        Some(
            ports
                .iter()
                .map(u16::to_string)
                .collect::<Vec<_>>()
                .join(", "),
        )
    }
}

/// `{ "br0", "br1" }` for `iifname`, or `"br0"` for a single interface.
fn lan_interface_match(interfaces: &[String]) -> Option<String> {
    match interfaces {
        [] => None,
        [single] => Some(format!("\"{single}\"")),
        many => Some(format!(
            "{{ {} }}",
            many.iter()
                .map(|name| format!("\"{name}\""))
                .collect::<Vec<_>>()
                .join(", ")
        )),
    }
}

/// nftables comments are double-quoted strings; strip anything that could break
/// out of the quotes and cap the length.
fn sanitize_comment(text: &str) -> Option<String> {
    let cleaned: String = text
        .chars()
        .filter(|c| {
            c.is_ascii_alphanumeric()
                || matches!(
                    c,
                    ' ' | '-' | '_' | '.' | ':' | '/' | '(' | ')' | ',' | '+' | '#'
                )
        })
        .take(64)
        .collect();
    let cleaned = cleaned.trim().to_string();
    if cleaned.is_empty() {
        None
    } else {
        Some(cleaned)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::networking::model::{
        BridgeConfig, DhcpConfig, FirewallRule, InterfaceConfig, InterfaceRole, PortForward,
    };

    fn router_config() -> NetworkConfig {
        NetworkConfig {
            interfaces: vec![
                InterfaceConfig {
                    name: "eth0".to_string(),
                    role: InterfaceRole::Wan,
                    address: None,
                },
                InterfaceConfig {
                    name: "eth1".to_string(),
                    role: InterfaceRole::Lan,
                    address: None,
                },
            ],
            bridges: vec![BridgeConfig {
                name: "br0".to_string(),
                members: vec!["eth1".to_string()],
                address: Some("192.168.1.1/24".to_string()),
                stp: false,
                comment: String::new(),
            }],
            dhcp: DhcpConfig {
                interface: "br0".to_string(),
                ..DhcpConfig::default()
            },
            ..NetworkConfig::default()
        }
    }

    #[test]
    fn renders_a_single_inet_table_with_drop_policy() {
        let ruleset = render(&router_config());
        assert!(ruleset.contains("table inet stackstack {"));
        assert!(ruleset.contains("type filter hook input priority filter; policy drop;"));
        assert!(ruleset.contains("type filter hook forward priority filter; policy drop;"));
        assert!(ruleset.contains("type filter hook output priority filter; policy accept;"));
        assert!(ruleset.contains("elements = { 192.168.1.0/24 }"));
    }

    #[test]
    fn management_ports_are_reachable_from_the_lan() {
        let ruleset = render(&router_config());
        // Ports are emitted in the configured order.
        assert!(
            ruleset.contains("iifname \"br0\" tcp dport { 22, 8553 } accept"),
            "{ruleset}"
        );
    }

    #[test]
    fn masquerade_only_when_a_wan_exists() {
        let mut config = router_config();
        assert!(render(&config).contains("oifname \"eth0\" masquerade"));

        config.interfaces[0].role = InterfaceRole::Unused;
        let ruleset = render(&config);
        assert!(!ruleset.contains("masquerade"));
        assert!(ruleset.contains("NAT is not applied"));
    }

    #[test]
    fn port_forwards_dnat_and_permit_the_forwarded_flow() {
        let mut config = router_config();
        config.port_forwards.push(PortForward {
            id: "web".to_string(),
            protocol: "tcp".to_string(),
            external_port: 443,
            internal_ip: "192.168.1.10".to_string(),
            internal_port: 8443,
            comment: "web".to_string(),
            enabled: true,
        });
        let ruleset = render(&config);
        assert!(
            ruleset.contains("iifname \"eth0\" tcp dport 443 dnat to 192.168.1.10:8443"),
            "{ruleset}"
        );
        assert!(ruleset.contains("iifname \"eth0\" ct status dnat accept"));
    }

    #[test]
    fn disabled_port_forwards_are_omitted_entirely() {
        let mut config = router_config();
        config.port_forwards.push(PortForward {
            id: "web".to_string(),
            protocol: "tcp".to_string(),
            external_port: 443,
            internal_ip: "192.168.1.10".to_string(),
            internal_port: 443,
            comment: String::new(),
            enabled: false,
        });
        let ruleset = render(&config);
        assert!(!ruleset.contains("dnat to"));
        assert!(!ruleset.contains("ct status dnat"));
    }

    #[test]
    fn rule_without_a_source_defaults_to_the_lan_set() {
        let mut config = router_config();
        config.firewall.rules.push(FirewallRule {
            id: "web".to_string(),
            action: crate::networking::model::FirewallAction::Accept,
            protocol: "tcp".to_string(),
            port: Some(8080),
            source: None,
            comment: "dashboard".to_string(),
            enabled: true,
        });
        let ruleset = render(&config);
        assert!(
            ruleset.contains("ip saddr @lan_nets tcp dport 8080 accept comment \"dashboard\""),
            "{ruleset}"
        );
    }

    #[test]
    fn explicit_source_is_normalised_to_the_network_address() {
        let mut config = router_config();
        config.firewall.rules.push(FirewallRule {
            id: "guest".to_string(),
            action: crate::networking::model::FirewallAction::Accept,
            protocol: "tcp".to_string(),
            port: Some(443),
            source: Some("10.0.0.99/24".to_string()),
            comment: String::new(),
            enabled: true,
        });
        let ruleset = render(&config);
        assert!(ruleset.contains("ip saddr 10.0.0.0/24 tcp dport 443 accept"));
        assert!(!ruleset.contains("10.0.0.99"));
    }

    #[test]
    fn comments_cannot_break_out_of_their_quotes() {
        let mut config = router_config();
        config.port_forwards.push(PortForward {
            id: "evil".to_string(),
            protocol: "tcp".to_string(),
            external_port: 80,
            internal_ip: "192.168.1.10".to_string(),
            internal_port: 80,
            comment: "x\" ; flush ruleset; #".to_string(),
            enabled: true,
        });
        let ruleset = render(&config);

        let line = ruleset
            .lines()
            .find(|line| line.contains("comment"))
            .expect("a comment line");
        let quoted = line
            .split_once("comment \"")
            .expect("quoted comment")
            .1
            .strip_suffix('"')
            .expect("closed comment");

        // The injected quote is gone (so the string cannot be closed early) and
        // so is the command separator.
        assert!(!quoted.contains('"'), "{line}");
        assert!(!quoted.contains(';'), "{line}");
        assert!(quoted.contains("flush ruleset"), "{line}");
    }

    #[test]
    fn a_lan_without_addresses_falls_back_to_interface_matching() {
        let mut config = router_config();
        config.bridges.clear();
        config.interfaces[1].role = InterfaceRole::Lan;
        config.interfaces[1].address = None;
        let ruleset = render(&config);
        assert!(!ruleset.contains("set lan_nets"));
        assert!(ruleset.contains("iifname \"eth1\" accept"), "{ruleset}");
    }

    #[test]
    fn two_lan_interfaces_render_as_a_set_both_places() {
        let mut config = router_config();
        config.bridges.push(BridgeConfig {
            name: "br1".to_string(),
            members: vec!["eth1".to_string()],
            address: Some("10.20.0.1/24".to_string()),
            stp: false,
            comment: String::new(),
        });
        let ruleset = render(&config);
        assert!(
            ruleset.contains("iifname { \"br0\", \"br1\" } udp dport 67 accept"),
            "{ruleset}"
        );
        assert!(
            ruleset.contains("192.168.1.0/24, 10.20.0.0/24"),
            "{ruleset}"
        );
    }
}
