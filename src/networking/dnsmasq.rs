//! dnsmasq configuration generation (DHCP, and DNS only when unbound is off).
//!
//! When unbound is enabled dnsmasq is deliberately reduced to a DHCP server:
//! `port=0` stops it binding :53 at all, so the two daemons can never fight over
//! the resolver port. `dhcp-option=option:dns-server` then points clients at
//! whatever `dns.listen` advertises.

use std::fmt::Write;

use crate::networking::ipmath::Ipv4Net;
use crate::networking::model::NetworkConfig;

pub fn render(config: &NetworkConfig) -> String {
    let mut out = String::with_capacity(1024);
    let _ = writeln!(
        out,
        "# Generated by stack-stack. Manual edits are overwritten."
    );

    // DNS ownership. The port is always written explicitly: the base fragment
    // in /etc/dnsmasq.d is inert (`port=0`) so a freshly enabled unit cannot
    // steal :53, and this generated file (read after it) is what decides the
    // real answer — 0 when unbound owns DNS, 53 when dnsmasq is the resolver.
    if config.dns.enabled {
        let _ = writeln!(out, "# DNS is served by unbound; dnsmasq is DHCP-only.");
        let _ = writeln!(out, "port=0");
    } else {
        let _ = writeln!(out, "port=53");
        if !config.dns.upstreams.is_empty() {
            let _ = writeln!(out, "no-resolv");
            for upstream in &config.dns.upstreams {
                let _ = writeln!(out, "server={upstream}");
            }
        }
    }

    if !config.dhcp.domain.is_empty() {
        let _ = writeln!(out, "domain={}", config.dhcp.domain);
    }
    let _ = writeln!(out, "domain-needed");
    let _ = writeln!(out, "bogus-priv");
    let _ = writeln!(out, "bind-dynamic");

    let serving = config.dhcp.enabled && !config.dhcp.interface.is_empty();
    if !serving {
        // No `dhcp-range` means no leases are ever offered, which is the
        // cleanest way to leave DHCP switched off.
        let _ = writeln!(out, "# DHCP is disabled");
        return out;
    }

    let Some(subnet) = subnet_for(config, &config.dhcp.interface) else {
        let _ = writeln!(
            out,
            "# interface has no static address; DHCP not configured"
        );
        return out;
    };
    let _ = writeln!(out, "interface={}", config.dhcp.interface);
    let _ = writeln!(out, "dhcp-authoritative");

    let netmask = subnet.netmask();
    let lease = sanitize_lease(&config.dhcp.lease);
    let _ = writeln!(
        out,
        "dhcp-range={},{},{},{}",
        config.dhcp.range_start, config.dhcp.range_end, netmask, lease
    );

    if !config.dhcp.gateway.is_empty() {
        let _ = writeln!(out, "dhcp-option=option:router,{}", config.dhcp.gateway);
    }
    if !config.dhcp.dns_servers.is_empty() {
        let _ = writeln!(
            out,
            "dhcp-option=option:dns-server,{}",
            config.dhcp.dns_servers.join(",")
        );
    }
    if !config.dhcp.domain.is_empty() {
        let _ = writeln!(out, "dhcp-option=option:domain-name,{}", config.dhcp.domain);
    }

    for reservation in &config.dhcp.reservations {
        let name = sanitize_hostname(&reservation.name);
        if name.is_empty() {
            let _ = writeln!(out, "dhcp-host={},{}", reservation.mac, reservation.ip);
        } else {
            let _ = writeln!(
                out,
                "dhcp-host={},{},{}",
                reservation.mac, reservation.ip, name
            );
        }
    }

    out
}

fn subnet_for(config: &NetworkConfig, interface: &str) -> Option<Ipv4Net> {
    config
        .bridges
        .iter()
        .find(|bridge| bridge.name == interface)
        .and_then(|bridge| bridge.address.as_deref())
        .or_else(|| {
            config
                .vlans
                .iter()
                .find(|vlan| vlan.name == interface)
                .and_then(|vlan| vlan.address.as_deref())
        })
        .or_else(|| {
            config
                .interfaces
                .iter()
                .find(|iface| iface.name == interface)
                .and_then(|iface| iface.address.as_deref())
        })
        .and_then(|address| Ipv4Net::parse(address).ok())
}

/// dnsmasq accepts `infinite` or `<digits><s|m|h|d|w>`. Anything that does not
/// match exactly is replaced by the default rather than being partially
/// stripped into something the operator did not ask for.
fn sanitize_lease(raw: &str) -> String {
    let lowered = raw.trim().to_ascii_lowercase();
    if lowered == "infinite" {
        return lowered;
    }

    let split = lowered
        .char_indices()
        .find(|(_, c)| !c.is_ascii_digit())
        .map(|(index, _)| index)
        .unwrap_or(lowered.len());
    let (digits, suffix) = lowered.split_at(split);

    let suffix_ok = suffix.is_empty() || matches!(suffix, "s" | "m" | "h" | "d" | "w");
    if digits.is_empty() || !suffix_ok {
        "12h".to_string()
    } else {
        format!("{digits}{suffix}")
    }
}

fn sanitize_hostname(raw: &str) -> String {
    raw.chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '_')
        .take(63)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::networking::model::{
        BridgeConfig, DhcpConfig, DhcpReservation, DnsConfig, InterfaceConfig, InterfaceRole,
    };

    fn router_config() -> NetworkConfig {
        NetworkConfig {
            interfaces: vec![
                InterfaceConfig {
                    name: "eth0".to_string(),
                    role: InterfaceRole::Wan,
                    address: None,
                },
                InterfaceConfig {
                    name: "eth1".to_string(),
                    role: InterfaceRole::Lan,
                    address: None,
                },
            ],
            bridges: vec![BridgeConfig {
                name: "br0".to_string(),
                members: vec!["eth1".to_string()],
                address: Some("192.168.1.1/24".to_string()),
                stp: false,
                comment: String::new(),
            }],
            dhcp: DhcpConfig {
                enabled: true,
                interface: "br0".to_string(),
                range_start: "192.168.1.100".to_string(),
                range_end: "192.168.1.250".to_string(),
                lease: "12h".to_string(),
                gateway: "192.168.1.1".to_string(),
                dns_servers: vec!["192.168.1.1".to_string()],
                ..DhcpConfig::default()
            },
            ..NetworkConfig::default()
        }
    }

    #[test]
    fn unbound_owns_port_53_when_enabled() {
        let rendered = render(&router_config());
        assert!(rendered.contains("port=0"), "{rendered}");
        assert!(!rendered.contains("no-resolv"));
    }

    #[test]
    fn dnsmasq_resolves_when_unbound_is_off() {
        let mut config = router_config();
        config.dns = DnsConfig {
            enabled: false,
            upstreams: vec!["1.1.1.1".to_string(), "9.9.9.9".to_string()],
            ..DnsConfig::default()
        };
        let rendered = render(&config);
        assert!(rendered.contains("no-resolv"));
        assert!(rendered.contains("server=1.1.1.1"));
        assert!(!rendered.contains("port=0"));
        // The port is explicit so it overrides the inert base fragment.
        assert!(rendered.contains("port=53"), "{rendered}");
    }

    #[test]
    fn dhcp_range_uses_the_subnet_mask_not_the_prefix() {
        let rendered = render(&router_config());
        assert!(
            rendered.contains("dhcp-range=192.168.1.100,192.168.1.250,255.255.255.0,12h"),
            "{rendered}"
        );
        assert!(rendered.contains("dhcp-option=option:router,192.168.1.1"));
        assert!(rendered.contains("dhcp-option=option:dns-server,192.168.1.1"));
        assert!(rendered.contains("interface=br0"));
        assert!(rendered.contains("dhcp-authoritative"));
    }

    #[test]
    fn disabled_dhcp_emits_no_range() {
        let mut config = router_config();
        config.dhcp.enabled = false;
        let rendered = render(&config);
        assert!(!rendered.contains("dhcp-range"));
        assert!(!rendered.contains("dhcp-authoritative"));
        assert!(rendered.contains("# DHCP is disabled"));
    }

    #[test]
    fn reservations_become_dhcp_host_lines() {
        let mut config = router_config();
        config.dhcp.reservations = vec![
            DhcpReservation {
                mac: "aa:bb:cc:dd:ee:ff".to_string(),
                ip: "192.168.1.10".to_string(),
                name: "nas".to_string(),
            },
            DhcpReservation {
                mac: "11:22:33:44:55:66".to_string(),
                ip: "192.168.1.11".to_string(),
                name: String::new(),
            },
        ];
        let rendered = render(&config);
        assert!(rendered.contains("dhcp-host=aa:bb:cc:dd:ee:ff,192.168.1.10,nas"));
        assert!(rendered.contains("dhcp-host=11:22:33:44:55:66,192.168.1.11\n"));
    }

    #[test]
    fn lease_is_sanitised_and_defaults() {
        assert_eq!(sanitize_lease("12h"), "12h");
        assert_eq!(sanitize_lease("30m"), "30m");
        assert_eq!(sanitize_lease("3600"), "3600");
        assert_eq!(sanitize_lease("infinite"), "infinite");
        // Junk is replaced wholesale, never partially stripped into a valid
        // but unintended lease.
        assert_eq!(sanitize_lease("1;rm -rf /"), "12h");
        assert_eq!(sanitize_lease("12hours"), "12h");
        assert_eq!(sanitize_lease("   "), "12h");
    }
}
