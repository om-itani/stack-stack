//! cloudflared tunnel configuration generation.
//!
//! Cloudflare terminates TLS at its edge, so a tunnel needs no local
//! certificate at all: this is the "https for *.example.com" story without
//! opening a single inbound port. Ingress rules are emitted in order, which is
//! significant — cloudflared matches the first rule that applies, so the
//! catch-all `http_status:404` must stay last.

use std::fmt::Write;

use crate::networking::model::NetworkConfig;

/// The UI's own port, used when the tunnel is asked to publish it.
const UI_SERVICE: &str = "http://127.0.0.1:8553";

pub fn render(config: &NetworkConfig) -> String {
    let tunnel = &config.tunnel;
    let mut out = String::with_capacity(1024);

    let _ = writeln!(
        out,
        "# Generated by stack-stack. Manual edits are overwritten."
    );
    let _ = writeln!(out, "tunnel: {}", sanitize_identifier(&tunnel.tunnel_id));
    let _ = writeln!(
        out,
        "credentials-file: {}",
        yaml_scalar(tunnel.credentials_file.trim())
    );
    let _ = writeln!(out, "ingress:");

    for ingress in &tunnel.ingress {
        let _ = writeln!(out, "  - hostname: {}", yaml_scalar(&ingress.hostname));
        let _ = writeln!(out, "    service: {}", yaml_scalar(&ingress.service));
        if let Some(comment) = comment(&ingress.comment) {
            let _ = writeln!(out, "    originRequest:");
            let _ = writeln!(out, "      # {comment}");
        }
    }

    if tunnel.expose_ui {
        let _ = writeln!(out, "  # fallback: the stack-stack UI itself");
        let _ = writeln!(out, "  - service: {UI_SERVICE}");
    }

    // Mandatory catch-all. Cloudflared refuses to start without one.
    let _ = writeln!(out, "  - service: http_status:404");
    out
}

/// Tunnel ids are UUIDs; tunnel names are DNS-ish. Both are safe in the subset
/// cloudflared accepts, so strip anything else rather than quoting it.
fn sanitize_identifier(raw: &str) -> String {
    let cleaned: String = raw
        .trim()
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'))
        .take(64)
        .collect();
    if cleaned.is_empty() {
        "stack-stack".to_string()
    } else {
        cleaned
    }
}

/// YAML scalar that is safe to emit unquoted where possible and correctly
/// escaped when not.
fn yaml_scalar(value: &str) -> String {
    let needs_quotes = value.is_empty()
        || value.chars().any(|c| {
            !(c.is_ascii_alphanumeric()
                || matches!(c, '.' | '-' | '_' | '/' | ':' | '@' | '+' | '='))
        });
    if !needs_quotes {
        return value.to_string();
    }
    let mut escaped = String::with_capacity(value.len() + 2);
    escaped.push('"');
    for c in value.chars() {
        match c {
            '"' => escaped.push_str("\\\""),
            '\\' => escaped.push_str("\\\\"),
            '\n' => escaped.push_str("\\n"),
            '\r' => escaped.push_str("\\r"),
            '\t' => escaped.push_str("\\t"),
            other => escaped.push(other),
        }
    }
    escaped.push('"');
    escaped
}

/// A YAML comment must stay on one line and cannot contain `#` sequences that
/// would change meaning; keep it to printable ASCII.
fn comment(raw: &str) -> Option<String> {
    let cleaned: String = raw
        .chars()
        .filter(|c| c.is_ascii_graphic() || *c == ' ')
        .take(80)
        .collect();
    let cleaned = cleaned.trim().to_string();
    if cleaned.is_empty() {
        None
    } else {
        Some(cleaned)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::networking::model::{TunnelConfig, TunnelIngress};

    fn tunnel_config() -> NetworkConfig {
        NetworkConfig {
            tunnel: TunnelConfig {
                enabled: true,
                tunnel_id: "0f9f0a3e-1234-4567-89ab-cdef01234567".to_string(),
                credentials_file: "/etc/cloudflared/credentials.json".to_string(),
                ingress: vec![
                    TunnelIngress {
                        hostname: "adguard.omaritani.dev".to_string(),
                        service: "http://192.168.1.10:8081".to_string(),
                        comment: "adguard dashboard".to_string(),
                    },
                    TunnelIngress {
                        hostname: "jellyfin.omaritani.dev".to_string(),
                        service: "http://192.168.1.20:8096".to_string(),
                        comment: String::new(),
                    },
                ],
                expose_ui: false,
            },
            ..NetworkConfig::default()
        }
    }

    #[test]
    fn renders_tunnel_identity_and_ordered_ingress() {
        let yaml = render(&tunnel_config());
        assert!(yaml.contains("tunnel: 0f9f0a3e-1234-4567-89ab-cdef01234567"));
        assert!(yaml.contains("credentials-file: /etc/cloudflared/credentials.json"));
        assert!(yaml.contains("  - hostname: adguard.omaritani.dev"));
        assert!(yaml.contains("    service: http://192.168.1.10:8081"));

        // The catch-all must be the final rule.
        let last_rule = yaml
            .lines()
            .rfind(|line| line.trim_start().starts_with("- "))
            .expect("a rule");
        assert_eq!(last_rule.trim(), "- service: http_status:404");
    }

    #[test]
    fn expose_ui_adds_a_fallback_before_the_404() {
        let mut config = tunnel_config();
        config.tunnel.expose_ui = true;
        let yaml = render(&config);
        let ui = yaml.find(UI_SERVICE).expect("ui service");
        let fallback = yaml.find("http_status:404").expect("fallback");
        assert!(ui < fallback, "{yaml}");
    }

    #[test]
    fn quoting_only_happens_when_needed() {
        assert_eq!(yaml_scalar("http://10.0.0.1:80"), "http://10.0.0.1:80");
        assert_eq!(
            yaml_scalar("/etc/cloudflared/x.json"),
            "/etc/cloudflared/x.json"
        );
        assert_eq!(yaml_scalar("has space"), "\"has space\"");
        assert_eq!(yaml_scalar("with\"quote"), "\"with\\\"quote\"");
    }

    #[test]
    fn credentials_path_with_spaces_is_quoted() {
        let mut config = tunnel_config();
        config.tunnel.credentials_file = "/etc/cloud flared/creds.json".to_string();
        let yaml = render(&config);
        assert!(
            yaml.contains("credentials-file: \"/etc/cloud flared/creds.json\""),
            "{yaml}"
        );
    }

    #[test]
    fn tunnel_id_is_sanitised() {
        let mut config = tunnel_config();
        config.tunnel.tunnel_id = "abc\n  defined: y".to_string();
        let yaml = render(&config);
        assert!(yaml.contains("tunnel: abcdefinedy"), "{yaml}");
        assert!(!yaml.contains("tunnel: abc\n"));
    }

    #[test]
    fn empty_tunnel_id_still_renders_a_placeholder() {
        let mut config = tunnel_config();
        config.tunnel.tunnel_id = "   ".to_string();
        assert!(render(&config).contains("tunnel: stack-stack"));
    }
}
