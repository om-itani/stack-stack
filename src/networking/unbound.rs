//! unbound configuration generation.
//!
//! unbound is the whole DNS story: recursive resolver (or forwarder), DNSSEC
//! validator, local rewrite authority for internal names, and the ad/tracker
//! sinkhole. There is no second resolver in the stack.
//!
//! Two rewrite shapes are supported, and they are genuinely different things:
//!
//! * an exact host becomes its own `static` zone, and
//! * a `*.domain` entry becomes a `redirect` zone at the domain apex, which
//!   answers every name in the subtree with the apex's record.

use std::fmt::Write;

use crate::networking::model::NetworkConfig;

/// Default DNSSEC trust anchor maintained by unbound itself.
const TRUST_ANCHOR: &str = "/var/lib/unbound/root.key";

pub fn render(config: &NetworkConfig) -> String {
    let dns = &config.dns;
    let mut out = String::with_capacity(2048);

    let _ = writeln!(
        out,
        "# Generated by stack-stack. Manual edits are overwritten."
    );
    let _ = writeln!(out, "server:");

    let _ = writeln!(out, "    verbosity: 1");
    let _ = writeln!(out, "    do-daemonize: no");
    let _ = writeln!(out, "    do-ip4: yes");
    let _ = writeln!(out, "    do-ip6: no");
    let _ = writeln!(out, "    do-udp: yes");
    let _ = writeln!(out, "    do-tcp: yes");
    let _ = writeln!(out, "    port: 53");

    for address in &dns.listen {
        let _ = writeln!(out, "    interface: {address}");
    }

    let _ = writeln!(out, "    access-control: 127.0.0.0/8 allow");
    for net in config.lan_networks() {
        let _ = writeln!(out, "    access-control: {} allow", net.network_cidr());
    }
    if config.lan_networks().is_empty() {
        let _ = writeln!(
            out,
            "    # no LAN subnet configured; only loopback clients are allowed"
        );
    }
    // Everything not listed above is refused, which is unbound's default.

    let _ = writeln!(out, "    hide-identity: yes");
    let _ = writeln!(out, "    hide-version: yes");
    let _ = writeln!(out, "    harden-glue: yes");
    let _ = writeln!(out, "    harden-dnssec-stripped: yes");
    let _ = writeln!(out, "    harden-below-nxdomain: yes");
    let _ = writeln!(out, "    harden-referral-path: yes");
    let _ = writeln!(out, "    use-caps-for-id: yes");
    let _ = writeln!(out, "    aggressive-nsec: yes");
    let _ = writeln!(out, "    prefetch: yes");
    let _ = writeln!(out, "    prefetch-key: yes");
    let _ = writeln!(
        out,
        "    qname-minimisation: {}",
        yes_no(dns.qname_minimisation)
    );
    let _ = writeln!(out, "    edns-buffer-size: 1232");

    let _ = writeln!(out, "    cache-min-ttl: {}", dns.cache_min_ttl);
    let _ = writeln!(out, "    cache-max-ttl: {}", dns.cache_max_ttl);
    let _ = writeln!(out, "    msg-cache-size: {}m", dns.cache_size_mb);
    let _ = writeln!(
        out,
        "    rrset-cache-size: {}m",
        dns.cache_size_mb.saturating_mul(2)
    );
    let _ = writeln!(out, "    num-threads: {}", dns.threads.max(1));
    if dns.threads > 1 {
        let _ = writeln!(out, "    so-reuseport: yes");
    }

    if dns.dnssec {
        let _ = writeln!(out, "    auto-trust-anchor-file: \"{TRUST_ANCHOR}\"");
        let _ = writeln!(out, "    val-log-level: 1");
    }

    render_rewrites(&mut out, config);
    render_blocks(&mut out, config);

    if let Some(blocklist) = &dns.blocklist_file
        && !blocklist.trim().is_empty()
    {
        let _ = writeln!(out, "    include: \"{}\"", blocklist.trim());
    }

    if !dns.upstreams.is_empty() {
        let _ = writeln!(out);
        let _ = writeln!(out, "forward-zone:");
        let _ = writeln!(out, "    name: \".\"");
        for upstream in &dns.upstreams {
            let _ = writeln!(out, "    forward-addr: {upstream}");
        }
    }

    out
}

fn render_rewrites(out: &mut String, config: &NetworkConfig) {
    let dns = &config.dns;
    if dns.rewrites.is_empty() {
        return;
    }

    let _ = writeln!(out);
    let _ = writeln!(out, "    # local rewrites");
    for rewrite in &dns.rewrites {
        let host = rewrite.host.trim().to_ascii_lowercase();
        let address = rewrite.address.trim();

        match host.strip_prefix("*.") {
            Some(apex) => {
                // `redirect` answers every name in the zone with the apex
                // record, which is exactly wildcard behaviour.
                let _ = writeln!(out, "    local-zone: \"{apex}.\" redirect");
                let _ = writeln!(out, "    local-data: \"{apex}. 300 IN A {address}\"");
            }
            None => {
                let _ = writeln!(out, "    local-zone: \"{host}.\" static");
                let _ = writeln!(out, "    local-data: \"{host}. 300 IN A {address}\"");
            }
        }
    }
}

fn render_blocks(out: &mut String, config: &NetworkConfig) {
    let dns = &config.dns;
    if dns.blocked_domains.is_empty() {
        return;
    }

    // A blocked domain must not duplicate a rewrite zone: unbound rejects a
    // zone declared twice, and the rewrite is the more specific intent.
    let rewrites: Vec<String> = dns
        .rewrites
        .iter()
        .map(|rewrite| {
            rewrite
                .host
                .trim()
                .trim_start_matches("*.")
                .trim_end_matches('.')
                .to_ascii_lowercase()
        })
        .collect();

    let _ = writeln!(out);
    let _ = writeln!(out, "    # sinkhole");
    for domain in &dns.blocked_domains {
        let normalised = domain.trim().trim_end_matches('.').to_ascii_lowercase();
        if normalised.is_empty() || rewrites.iter().any(|zone| zone == &normalised) {
            continue;
        }
        // A local-zone covers the name and its whole subtree.
        let _ = writeln!(out, "    local-zone: \"{normalised}.\" always_nxdomain");
    }
}

fn yes_no(value: bool) -> &'static str {
    if value { "yes" } else { "no" }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::networking::model::{
        BridgeConfig, DnsConfig, DnsRewrite, InterfaceConfig, InterfaceRole,
    };

    fn dns_config() -> NetworkConfig {
        NetworkConfig {
            interfaces: vec![
                InterfaceConfig {
                    name: "eth0".to_string(),
                    role: InterfaceRole::Wan,
                    address: None,
                },
                InterfaceConfig {
                    name: "eth1".to_string(),
                    role: InterfaceRole::Lan,
                    address: None,
                },
            ],
            bridges: vec![BridgeConfig {
                name: "br0".to_string(),
                members: vec!["eth1".to_string()],
                address: Some("192.168.1.1/24".to_string()),
                stp: false,
                comment: String::new(),
            }],
            dns: DnsConfig {
                enabled: true,
                listen: vec!["192.168.1.1".to_string(), "127.0.0.1".to_string()],
                upstreams: vec!["1.1.1.1".to_string(), "9.9.9.9".to_string()],
                ..DnsConfig::default()
            },
            ..NetworkConfig::default()
        }
    }

    #[test]
    fn recursive_and_forwarding_modes_render() {
        let rendered = render(&dns_config());
        assert!(rendered.contains("\nserver:\n"), "{rendered}");
        assert!(rendered.contains("interface: 192.168.1.1"));
        assert!(rendered.contains("interface: 127.0.0.1"));
        assert!(rendered.contains("access-control: 192.168.1.0/24 allow"));
        assert!(rendered.contains("forward-zone:"));
        assert!(rendered.contains("forward-addr: 1.1.1.1"));
        assert!(rendered.contains("auto-trust-anchor-file"));
    }

    #[test]
    fn no_upstreams_means_pure_recursion() {
        let mut config = dns_config();
        config.dns.upstreams.clear();
        let rendered = render(&config);
        assert!(!rendered.contains("forward-zone:"));
    }

    #[test]
    fn exact_rewrite_becomes_a_static_zone() {
        let mut config = dns_config();
        config.dns.rewrites.push(DnsRewrite {
            host: "adguard.omaritani.dev".to_string(),
            address: "192.168.1.10".to_string(),
            comment: String::new(),
        });
        let rendered = render(&config);
        assert!(rendered.contains("local-zone: \"adguard.omaritani.dev.\" static"));
        assert!(rendered.contains("local-data: \"adguard.omaritani.dev. 300 IN A 192.168.1.10\""));
    }

    #[test]
    fn wildcard_rewrite_becomes_a_redirect_zone() {
        let mut config = dns_config();
        config.dns.rewrites.push(DnsRewrite {
            host: "*.omaritani.dev".to_string(),
            address: "192.168.1.1".to_string(),
            comment: String::new(),
        });
        let rendered = render(&config);
        assert!(
            rendered.contains("local-zone: \"omaritani.dev.\" redirect"),
            "{rendered}"
        );
        assert!(rendered.contains("local-data: \"omaritani.dev. 300 IN A 192.168.1.1\""));
        assert!(!rendered.contains("\"*.omaritani.dev.\""));
    }

    #[test]
    fn blocked_domains_become_always_nxdomain_zones() {
        let mut config = dns_config();
        config.dns.blocked_domains = vec!["ads.example.com".to_string()];
        let rendered = render(&config);
        assert!(rendered.contains("local-zone: \"ads.example.com.\" always_nxdomain"));
    }

    #[test]
    fn a_blocked_domain_that_is_also_a_rewrite_zone_is_skipped() {
        let mut config = dns_config();
        config.dns.rewrites.push(DnsRewrite {
            host: "*.omaritani.dev".to_string(),
            address: "192.168.1.1".to_string(),
            comment: String::new(),
        });
        config.dns.blocked_domains = vec!["omaritani.dev".to_string()];
        let rendered = render(&config);
        assert!(!rendered.contains("always_nxdomain"), "{rendered}");
    }

    #[test]
    fn blocklist_file_is_included_when_present() {
        let mut config = dns_config();
        config.dns.blocklist_file = Some("/etc/unbound/blocklist.conf".to_string());
        let rendered = render(&config);
        assert!(rendered.contains("include: \"/etc/unbound/blocklist.conf\""));
    }

    #[test]
    fn dnssec_can_be_switched_off() {
        let mut config = dns_config();
        config.dns.dnssec = false;
        assert!(!render(&config).contains("trust-anchor"));
    }
}
